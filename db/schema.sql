CREATE TABLE account (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
	name TEXT NOT NULL,
	balance_paise BIGINT NOT NULL CHECK(balance_paise >= 0),
	owner_uid TEXT NOT NULL,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE transfer (
	id BIGSERIAL PRIMARY KEY, 
	request_id UUID NOT NULL UNIQUE, 
	from_account_id BIGINT NOT NULL REFERENCES account(id), 
	to_account_id BIGINT NOT NULL REFERENCES account(id),
	amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
   	status VARCHAR(20) NOT NULL CHECK (status IN ('SUCCESS', 'FAILED', 'REVERSED')),
    	failure_reason TEXT,
    	reversed_by BIGINT REFERENCES transfer(id),
    	reversal_of BIGINT REFERENCES transfer(id),
    	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    	updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES account(id),
    transfer_id BIGINT NOT NULL REFERENCES transfer(id),
    message TEXT NOT NULL,
    channel VARCHAR(20) NOT NULL DEFAULT 'MOCK'
        CHECK (channel = 'MOCK'),
    status VARCHAR(20) NOT NULL DEFAULT 'CREATED'
        CHECK (status IN ('CREATED', 'FAILED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (account_id, transfer_id)
);

CREATE INDEX idx_account_owner_uid ON account(owner_uid);
CREATE INDEX idx_transfer_from_account ON transfer(from_account_id);
CREATE INDEX idx_transfer_to_account ON transfer(to_account_id);
CREATE INDEX idx_notification_account ON notification(account_id);
